"""What the scan-job service depends on. Concretes are named only in composition.py."""

from __future__ import annotations

from typing import Optional, Protocol

from scan_jobs.models import ArtifactInfo, MazdaSummary, PageText, RenderedPage, ScalaSummary, ScanRecord


class IScannerController(Protocol):
    """The dashboard's existing scan path. The physical lock lives behind it."""

    def run(self, key: str) -> dict: ...
    def output_path(self, key: str) -> Optional[str]: ...
    def scanner_name(self, key: str) -> str: ...


class IScanJobRepository(Protocol):
    def create(self, record: ScanRecord, created_ns: int, idempotency: Optional[tuple[str, str]],
               refuse_if_active: bool) -> tuple[ScanRecord, bool]: ...
    def transition(self, scan_id: str, status: str, **changes: object) -> ScanRecord: ...
    def set_mazda(self, scan_id: str, summary: MazdaSummary) -> ScanRecord: ...
    def idempotent_scan_id(self, scope: str, key: str) -> Optional[str]: ...
    def get(self, scan_id: str) -> Optional[ScanRecord]: ...
    def list_recent(self, limit: int, cursor: Optional[str]) -> tuple[list[ScanRecord], Optional[str]]: ...
    def bridge_starts_since(self, since_ns: int, scanner: Optional[str]) -> list[int]: ...
    def interrupt_active(self) -> int: ...
    def audit(self, scan_id: Optional[str], actor: str, event: str, detail: str = '') -> None: ...


class IScanArtifactStore(Protocol):
    def put_file(self, source_path: str, not_before_ns: int) -> tuple[str, str, int]: ...
    def read(self, sha256: str) -> bytes: ...
    def get_derived(self, sha256: str, name: str) -> Optional[bytes]: ...
    def put_derived(self, sha256: str, name: str, data: bytes) -> None: ...


class IScanDocumentReader(Protocol):
    def page_count(self, data: bytes, mime_type: str) -> int: ...
    def render_page(self, data: bytes, mime_type: str, page: int, rendition: str) -> RenderedPage: ...
    def page_text(self, data: bytes, mime_type: str, page: int) -> PageText: ...


class IMazdaVerdictProvider(Protocol):
    def summarize(self, record: ScanRecord) -> MazdaSummary: ...


class IScalaFilingProvider(Protocol):
    def summarize(self, record: ScanRecord) -> ScalaSummary: ...


class IBridgeAuthorizer(Protocol):
    def authorize(self, client_ip: str, headers: dict[str, str], scope: str) -> str: ...


__all__ = ['ArtifactInfo', 'IBridgeAuthorizer', 'IMazdaVerdictProvider', 'IScanArtifactStore',
           'IScalaFilingProvider', 'IScanDocumentReader', 'IScanJobRepository', 'IScannerController']
